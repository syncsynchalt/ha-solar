def bitflip(img: bytes) -> bytes:
    ''' flip white / black pixels '''
    out: list[int] = []
    for b in img:
        out.append(b ^ 0xff)
    return bytes(out)


def flip_row(row: bytes) -> list:
    ''' flip the bit order, also rotate the first six bits to the end '''
    as_str = ""
    for b in row:
        as_str = as_str + '{0:08b}'.format(b)
    rev = "".join(reversed(as_str))
    ''' move first six bits to the end, they're not displayed '''
    rev = rev[6:] + rev[0:6]
    out = []
    while len(rev):
        out.append(int(rev[0:8], 2))
        rev = rev[8:]
    return out


def hflip(h: int, w: int, bin: bytes) -> bytes:
    out = []
    rowlen = w // 8
    for row in range(h):
        row = bin[row*rowlen:row*rowlen+rowlen]
        out = out + flip_row(row)
    return bytes(out)


